import assert from "node:assert/strict";
import test from "node:test";
import { IDBFactory } from "fake-indexeddb";
import { createShift, emptyData, repairShiftActivityIds, markRemainingTasksManagementBlocked, taskOutcomeSummary, deliverySummary, grossWagesPence, workMilesTenths } from "../lib/domain.ts";
import { loadDataSafely, saveData, restoreRecoveryData, resetStorageSessionForTests, testIndexedDbRecoveryReadiness } from "../lib/storage.ts";
import { localSaveSnapshot } from "../lib/localSaveStatus.ts";
import { encryptCheckpoint, decryptCheckpoint, type HostedCapability } from "../lib/hostedBackup.ts";

test("offline shift, failed write, reload and encrypted restore preserve the last verified records", async () => {
  const options = { factory: new IDBFactory(), localStorage: null, databaseName: "completion-recovery-journey" };
  assert.notEqual((await loadDataSafely(options)).status, "failed");
  const data = emptyData();
  const shift = repairShiftActivityIds(createShift(data.settings, new Date("2026-09-30T08:00:00.000Z")));
  data.shifts.push(shift);
  await saveData(data, options);
  shift.activities?.push({ id: "delivery-run", shiftId: shift.id, type: "single_delivery", start: "2026-09-30T09:00:00.000Z", end: "2026-09-30T09:30:00.000Z", customerDeliveries: 1, deliveryEventId: "delivery-event", customerEvents: [{ timestamp: "2026-09-30T09:20:00.000Z", source: "manual_delivered", pointIndex: 0, latitude: 53.57, longitude: -2.88, accuracy: 8 }], routeEvidence: { status: "complete", startedAt: "2026-09-30T09:00:00.000Z", completedAt: "2026-09-30T09:30:00.000Z", points: [{ latitude: 53.57, longitude: -2.88, timestamp: "2026-09-30T09:20:00.000Z", accuracy: 8 }], recordedPointCount: 1, distanceMetres: 1200, gaps: [], issues: [], detail: "standard", retention: "90", expiresAt: null } });
  shift.deliveries.push({ id: "delivery-event", activityId: "delivery-run", type: "single", timestamp: "2026-09-30T09:20:00.000Z", reimbursementPence: shift.singleRatePence });
  shift.breaks.push({ id: "break", start: "2026-09-30T12:00:00.000Z", end: "2026-09-30T12:20:00.000Z" });
  shift.mileage.directTenths = 175;
  markRemainingTasksManagementBlocked(shift, "2026-09-30T14:50:00.000Z");
  shift.status = "completed"; shift.clockOut = "2026-09-30T15:00:00.000Z"; shift.updatedAt = shift.clockOut;
  await saveData(data, { ...options, recovery: true });
  const changed = structuredClone(data); changed.shifts[0].mileage.directTenths = 999;
  await assert.rejects(() => saveData(changed, { ...options, testHooks: { failWriteWithQuota: true } }));
  assert.equal(localSaveSnapshot().status, "failed");
  resetStorageSessionForTests(options.databaseName);
  const reloaded = await loadDataSafely(options);
  assert.notEqual(reloaded.status, "failed");
  if (reloaded.status === "failed") return;
  assert.equal(reloaded.data.shifts[0].mileage.directTenths, 175);
  const capability: HostedCapability = { version: 1, deviceId: "journey-device-abcdefghijklmnop", secret: "AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA", backupEnabled: true, createdAt: shift.clockIn };
  const encrypted = await encryptCheckpoint(reloaded.data, "Clock Out", capability);
  const recovered = await decryptCheckpoint(encrypted.bytes.buffer as ArrayBuffer, capability);
  await saveData(emptyData(), options);
  await restoreRecoveryData(recovered, options);
  assert.equal(localSaveSnapshot().status, "saved");
  resetStorageSessionForTests(options.databaseName);
  const restored = await loadDataSafely(options);
  assert.notEqual(restored.status, "failed");
  if (restored.status === "failed") return;
  const original = reloaded.data.shifts[0], result = restored.data.shifts[0];
  assert.deepEqual(taskOutcomeSummary(result), taskOutcomeSummary(original));
  assert.deepEqual(deliverySummary(result), deliverySummary(original));
  assert.equal(grossWagesPence(result), grossWagesPence(original));
  assert.equal(workMilesTenths(result), 175);
  assert.equal(result.activities?.find(item => item.id === "delivery-run")?.routeEvidence?.points.length, 1);
  assert.equal((await testIndexedDbRecoveryReadiness(options)).status, "ready");
});
